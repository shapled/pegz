// Helper function to escape strings for Zig code generation
fn escapeZigString(s: []const u8, allocator: std.mem.Allocator) ![]const u8 {
    var result = try std.ArrayList(u8).initCapacity(allocator, s.len * 2);
    errdefer {
        result.deinit(allocator);
    }

    for (s) |c| {
        switch (c) {
            '\\' => try result.appendSlice(allocator, "\\\\"),
            '"' => try result.appendSlice(allocator, "\\\""),
            '\n' => try result.appendSlice(allocator, "\\n"),
            '\r' => try result.appendSlice(allocator, "\\r"),
            '\t' => try result.appendSlice(allocator, "\\t"),
            else => {
                // Escape non-printable and non-ASCII characters
                if (c < 32 or c >= 127) {
                    try result.appendSlice(allocator, "\\x");
                    try result.append(allocator, std.fmt.digitToChar(c >> 4, .lower));
                    try result.append(allocator, std.fmt.digitToChar(c & 0xF, .lower));
                } else {
                    try result.append(allocator, c);
                }
            },
        }
    }

    return result.toOwnedSlice(allocator);
}

