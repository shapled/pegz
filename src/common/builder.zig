    fn writeRuleCode(self: *Builder, rule: *ast.Rule) !void {
        if (rule.name.value.len == 0) return;

        self.rule_name = rule.name.value;
        self.expr_index = 0;
        try self.pushArgsSet();

        // Collect all possible parameters from labels
        try self.collectParams(rule.expr);
        const all_params = self.getCurrentParams();

        // Generate action function for this rule
        try self.writer.print("// Action function for rule: {s}\n", .{rule.name.value});
        try self.writer.print("fn on{s}(c: *interpreter.Current", .{rule.name.value});

        // Add all parameters
        for (all_params.items) |param| {
            try self.writer.print(", {s}: interpreter.Value", .{param});
        }
        try self.writer.writeAll(") !interpreter.Value {\n");

        // Analyze which parameters are actually used in the action code
        const used_params = try self.analyzeUsedParams(rule.expr);

        // Check if 'c' parameter is used
        const c_is_used = for (used_params.items) |used| {
            if (std.mem.eql(u8, used, "c")) {
                break true;
            }
        } else false;

        // Add _ = c; if c is not used
        if (!c_is_used) {
            try self.writer.writeAll("    _ = c;\n");
        }

        // Add _ = param; only for UNUSED parameters to suppress unused warnings
        // This is Zig's standard way to mark parameters as intentionally unused
        for (all_params.items) |param| {
            const is_used = for (used_params.items) |used| {
                if (std.mem.eql(u8, used, param)) {
                    break true;
                }
            } else false;

            if (!is_used) {
                try self.writer.print("    _ = {s};\n", .{param});
            }
        }

        // Generate action code
        try self.writeExprCode(rule.expr);

        try self.writer.writeAll("}\n\n");
        self.popArgsSet();
    }

    /// Analyze which parameters are referenced in the action code
    fn analyzeUsedParams(self: *Builder, expr: *const ast.Expression) !std.ArrayList([]const u8) {
        var used = try std.ArrayList([]const u8).initCapacity(self.allocator, 0);
        errdefer used.deinit(self.allocator);

        // Collect action code from the expression
        var action_codes = try std.ArrayList([]const u8).initCapacity(self.allocator, 0);
        defer {
            for (action_codes.items) |code| {
                self.allocator.free(code);
            }
            action_codes.deinit(self.allocator);
        }

        try self.collectActionCode(expr, &action_codes);

        // Analyze each action code for parameter references
        for (action_codes.items) |code| {
            try self.findParamReferences(code, &used);
        }

        // Deduplicate and return
        var result = try std.ArrayList([]const u8).initCapacity(self.allocator, used.items.len);
        for (used.items) |param| {
            const already_exists = for (result.items) |p| {
                if (std.mem.eql(u8, p, param)) break true;
            } else false;
            if (!already_exists) {
                try result.append(self.allocator, param);
            }
        }
        return result;
    }

    /// Collect all action code strings from an expression
    fn collectActionCode(self: *Builder, expr: *const ast.Expression, codes: *std.ArrayList([]const u8)) !void {
        switch (expr.*) {
            .action => |act| {
                try codes.append(self.allocator, try self.allocator.dupe(u8, act.code.value));
                try self.collectActionCode(act.expr, codes);
            },
            .seq => |seq| {
                for (seq.exprs.items) |sub| {
                    try self.collectActionCode(sub, codes);
                }
            },
            .choice => |choice| {
                for (choice.alternatives.items) |alt| {
                    try self.collectActionCode(alt, codes);
                }
            },
            .labeled => |labeled| {
                try self.collectActionCode(labeled.expr, codes);
            },
            .zero_or_one => |z| try self.collectActionCode(z.expr, codes),
            .zero_or_more => |z| try self.collectActionCode(z.expr, codes),
            .one_or_more => |o| try self.collectActionCode(o.expr, codes),
            .and_expr => |and_expr| try self.collectActionCode(and_expr.expr, codes),
            .not => |not_expr| try self.collectActionCode(not_expr.expr, codes),
            else => {}, // Other types don't contain action code
        }
    }

    /// Find parameter references in code string
    fn findParamReferences(self: *Builder, code: []const u8, used: *std.ArrayList([]const u8)) !void {
        // Simple heuristic: find identifiers that match parameter names
        // Look for patterns like "param", "param.", "param("
        var i: usize = 0;
        while (i < code.len) {
            // Skip non-identifier characters
            if (!isIdentifierStart(code[i])) {
                i += 1;
                continue;
            }

            // Found identifier start
            const start = i;
            while (i < code.len and isIdentifierContinue(code[i])) {
                i += 1;
            }

            const ident = code[start..i];

            // Check if this is a parameter reference
            // (heuristic: identifier followed by '.', '(', or end of statement)
            if (i < code.len) {
                const next_char = code[i];
                if (next_char == '.' or next_char == '(' or next_char == ' ' or
                    next_char == '\n' or next_char == ',' or next_char == ';' or
                    next_char == ')' or next_char == '}' or next_char == '=') {
                    // Check if this identifier is a known parameter
                    // For now, assume any identifier could be a parameter
                    // In a more complete implementation, we'd check against self.params
                    try used.append(self.allocator, try self.allocator.dupe(u8, ident));
                }
            }
        }
    }

    fn isIdentifierStart(c: u8) bool {
        return (c >= 'a' and c <= 'z') or (c >= 'A' and c <= 'Z') or c == '_';
    }

    fn isIdentifierContinue(c: u8) bool {
        return isIdentifierStart(c) or (c >= '0' and c <= '9');
    }

    fn pushArgsSet(self: *Builder) !void {
        try self.args_stack.append(self.allocator, try std.ArrayList([]const u8).initCapacity(self.allocator, 0));
    }

    fn popArgsSet(self: *Builder) void {
        if (self.args_stack.items.len > 0) {
            var old_set = self.args_stack.orderedRemove(self.args_stack.items.len - 1);
            old_set.deinit(self.allocator);
        }
    }

    fn addArg(self: *Builder, arg: *ast.Identifier) !void {
        if (self.args_stack.items.len == 0) return;

        const current_set = &self.args_stack.items[self.args_stack.items.len - 1];
        try current_set.append(self.allocator, arg.value);
    }

    fn collectParams(self: *Builder, expr: *ast.Expression) !void {
        switch (expr.*) {
            .labeled => |labeled| {
                try self.addArg(labeled.label);
                try self.collectParams(labeled.expr);
            },
            .seq => |seq| {
                for (seq.exprs.items) |sub| {
                    try self.collectParams(sub);
                }
            },
            .choice => |choice| {
                for (choice.alternatives.items) |alt| {
                    try self.collectParams(alt);
                }
            },
            .action => |action| {
                try self.collectParams(action.expr);
            },
            // Other expression types don't have labels
            else => {},
        }
    }

    fn getCurrentParams(self: *Builder) std.ArrayList([]const u8) {
        if (self.args_stack.items.len == 0) {
            return std.ArrayList([]const u8).initCapacity(self.allocator, 0) catch unreachable;
        }
        return self.args_stack.items[self.args_stack.items.len - 1];
    }

    fn writeExprCode(self: *Builder, expr: *ast.Expression) !void {
        switch (expr.*) {
            .action => |act| {
                try self.writeExprCode(act.expr);
                try self.writeActionExprCode(act);
            },
            .and_code => |and_code| try self.writeAndCodeExprCode(and_code),
            .labeled => |labeled| {
                try self.addArg(labeled.label);
                try self.pushArgsSet();
                try self.writeExprCode(labeled.expr);
                self.popArgsSet();
            },
            .not_code => |not_code| try self.writeNotCodeExprCode(not_code),
            .and_expr => |and_expr| {
                try self.pushArgsSet();
                try self.writeExprCode(and_expr.expr);
                self.popArgsSet();
            },
            .choice => |choice| {
                for (choice.alternatives.items) |alt| {
                    try self.pushArgsSet();
                    try self.writeExprCode(alt);
                    self.popArgsSet();
                }
            },
            .not => |not_expr| {
                try self.pushArgsSet();
                try self.writeExprCode(not_expr.expr);
                self.popArgsSet();
            },
            .one_or_more => |one_or_more| {
                try self.pushArgsSet();
                try self.writeExprCode(one_or_more.expr);
                self.popArgsSet();
            },
            .recovery => |recovery| {
                try self.pushArgsSet();
                try self.writeExprCode(recovery.expr);
                try self.writeExprCode(recovery.recover_expr);
                self.popArgsSet();
            },
            .seq => |seq| {
                for (seq.exprs.items) |sub| {
                    try self.writeExprCode(sub);
                }
            },
            .state_code => |state_code| try self.writeStateCodeExprCode(state_code),
            .zero_or_more => |zero_or_more| {
                try self.pushArgsSet();
                try self.writeExprCode(zero_or_more.expr);
                self.popArgsSet();
            },
            .zero_or_one => |zero_or_one| {
                try self.pushArgsSet();
                try self.writeExprCode(zero_or_one.expr);
                self.popArgsSet();
            },
            else => {}, // Other types don't generate code
        }
    }

    fn writeActionExprCode(self: *Builder, act: *ast.ActionExpr) !void {
        // Write the user's action code
        // For now, we just extract the code and write it
        // TODO: Process the code to handle variable references
        const code = act.code.value;

        if (code.len > 2) { // Not just {}
            // Extract code between braces
            const inner_code = if (code.len > 2 and code[0] == '{')
                code[1 .. code.len-1]
            else
                code;

            // Write the code with proper indentation
            try self.writer.writeAll("    ");
            try self.writer.writeAll(inner_code);
            try self.writer.writeAll("\n");
        }
    }

    fn writeAndCodeExprCode(self: *Builder, and_code: *ast.AndCodeExpr) !void {
        if (and_code.func_ix > 0) {
            try self.writeFunc(CALL_PRED_FUNC_TEMPLATE, ON_PRED_FUNC_TEMPLATE, and_code.func_ix, and_code.code.value);
            and_code.func_ix = 0; // prevent duplicates
        }
    }

    fn writeNotCodeExprCode(self: *Builder, not_code: *ast.NotCodeExpr) !void {
        if (not_code.func_ix > 0) {
            try self.writeFunc(CALL_PRED_FUNC_TEMPLATE, ON_PRED_FUNC_TEMPLATE, not_code.func_ix, not_code.code.value);
            not_code.func_ix = 0; // prevent duplicates
        }
    }

    fn writeStateCodeExprCode(self: *Builder, state_code: *ast.StateCodeExpr) !void {
        if (state_code.func_ix > 0) {
            try self.writeFunc(CALL_STATE_FUNC_TEMPLATE, ON_STATE_FUNC_TEMPLATE, state_code.func_ix, state_code.code.value);
            state_code.func_ix = 0; // prevent duplicates
        }
    }

    fn writeFunc(self: *Builder, comptime call_template: []const u8, comptime func_template: []const u8, func_ix: usize, code: []const u8) !void {
        _ = func_ix;
        
        if (code.len <= 2) return; // empty code block {}

        // Remove braces and trim whitespace
        // const val = std.mem.trim(u8, code[1..code.len-1], " \t\r\n");

        // Generate arguments list
        var args_buffer: std.ArrayList(u8) = .empty;
        defer args_buffer.deinit(self.allocator);

        if (self.args_stack.items.len > 0) {
            const current_set = &self.args_stack.items[self.args_stack.items.len - 1];
            for (current_set.items, 0..) |arg, i| {
                if (i > 0) {
                    try args_buffer.appendSlice(self.allocator, ", ");
                }
                try args_buffer.appendSlice(self.allocator, arg);
            }
        }
        if (args_buffer.items.len > 0) {
            try args_buffer.appendSlice(self.allocator, " any");
        }

        const fn_name = self.rule_name;

        // Write function definition
        try self.writer.print(func_template,
            .{ self.options.receiver_name, fn_name, args_buffer.items });

        // Generate stack access arguments
        args_buffer.clearRetainingCapacity();
        var writer = std.io.Writer.Allocating.fromArrayList(self.allocator, &args_buffer).writer;

        if (self.args_stack.items.len > 0) {
            const current_set = &self.args_stack.items[self.args_stack.items.len - 1];
            for (current_set.items, 0..) |arg, i| {
                if (i > 0) {
                    try args_buffer.appendSlice(self.allocator, ", ");
                }

                try writer.print("\"{s}\"", .{arg});
            }
        }

        // Write function call
        try self.writer.print(call_template, .{ fn_name, "todo", args_buffer.items });
    }

    fn writeStaticCode(self: *Builder) !void {
        // Write ParserError enum
        try self.writer.writeAll("const ParserError = error{\n");
        try self.writer.writeAll("    ParseError,\n");
        try self.writer.writeAll("    UnexpectedToken,\n");
        try self.writer.writeAll("    MissingExpression,\n");
        try self.writer.writeAll("    UnterminatedExpression,\n");
        try self.writer.writeAll("    OutOfMemory,\n");
        try self.writer.writeAll("};\n\n");

        // Write basic Parser struct definition
        try self.writer.writeAll("/// Parser holds the state to parse PEG grammar into an abstract syntax tree (AST).\n");
        try self.writer.writeAll("pub const Parser = struct {\n");
        try self.writer.writeAll("    allocator: std.mem.Allocator,\n");
        try self.writer.writeAll("    filename: []const u8,\n");
        try self.writer.writeAll("    reader: *std.io.Reader,\n");

        // Scanner-related fields
        try self.writer.writeAll("    scanner: ?*Scanner,\n");  // Scanner will be defined in scanner.zig - optional pointer
        try self.writer.writeAll("    tok: Token,\n");        // Current token
        try self.writer.writeAll("    peek_tok: Token,\n");    // Peek token (next one in stream)

        // Debug and error handling fields
        try self.writer.writeAll("    debug: bool = false,\n");

        // Add scanner and token imports
        try self.writer.writeAll("\n");
        try self.writer.writeAll("    // Import scanner and token definitions\n");
        try self.writer.writeAll("    const Scanner = @import(\"scanner.zig\").Scanner;\n");
        try self.writer.writeAll("    const Token = @import(\"scanner.zig\").Token;\n");

        // Write init method (update to include filename and reader)
        try self.writer.writeAll("\n");
        try self.writer.writeAll("    pub fn init(allocator: std.mem.Allocator, filename: []const u8, reader: *std.io.Reader) Parser {\n");
        try self.writer.writeAll("        // Initialize with scanner = null and empty tokens\n");
        try self.writer.writeAll("        var init_tok = Token{\n");
        try self.writer.writeAll("            .id = .invalid,\n");  // Assume Token has an id field with enum type
        try self.writer.writeAll("            .lit = \"\",\n");     // Assume Token has a lit field
        try self.writer.writeAll("        };\n");
        try self.writer.writeAll("\n");
        try self.writer.writeAll("        return Parser{\n");
        try self.writer.writeAll("            .allocator = allocator,\n");
        try self.writer.writeAll("            .filename = filename,\n");
        try self.writer.writeAll("            .reader = reader,\n");
        try self.writer.writeAll("            .scanner = null,\n");
        try self.writer.writeAll("            .tok = init_tok,\n");
        try self.writer.writeAll("            .peek_tok = init_tok,\n");
        try self.writer.writeAll("        };\n");
        try self.writer.writeAll("    }\n");

        // Write parse method framework
        try self.writer.writeAll("\n");
        try self.writer.writeAll("    /// Parse parses the data from the reader and generates the AST\n");
        try self.writer.writeAll("    /// or returns an error if it fails. The filename is used as information\n");
        try self.writer.writeAll("    /// in the error messages.\n");
        try self.writer.writeAll("    pub fn parse(self: *Parser) !*ast.Grammar {\n");

        // Initialize scanner
        try self.writer.writeAll("        // Initialize scanner\n");
        try self.writer.writeAll("        self.scanner = try Scanner.init(self.allocator, self.filename, self.reader, null);\n");
        try self.writer.writeAll("        defer if (self.scanner) |scanner| scanner.deinit();\n");
        try self.writer.writeAll("\n");

        // Read first two tokens (current and peek)
        try self.writer.writeAll("        // Read first two tokens\n");
        try self.writer.writeAll("        self.read();\n");
        try self.writer.writeAll("        self.read();\n");
        try self.writer.writeAll("\n");

        // Call grammar rule (the start symbol of the PEG grammar)
        try self.writer.writeAll("        // Parse grammar using the root rule (Grammar)\n");
        try self.writer.writeAll("        const grammar = try self.grammar();\n");
        try self.writer.writeAll("\n");

        // Clean up and return
        try self.writer.writeAll("        // Return the parsed grammar\n");
        try self.writer.writeAll("        return grammar;\n");
        try self.writer.writeAll("    }\n");

        // Write deinit method
        try self.writer.writeAll("\n");
        try self.writer.writeAll("    pub fn deinit(_: *Parser) void {\n");
        try self.writer.writeAll("        // TODO: Implement cleanup logic\n");
        try self.writer.writeAll("    }\n");

        // Close Parser struct
        try self.writer.writeAll("};\n\n");

        // Write range table comment if needed
        if (self.range_table) {
            try self.writer.writeAll("// Range table code would be written here\n");
        }
    }

    pub fn deinit(self: *Builder) void {
        while (self.args_stack.items.len > 0) {
            var old_set = self.args_stack.orderedRemove(self.args_stack.items.len - 1);
            old_set.deinit(self.allocator);
        }
        self.args_stack.deinit(self.allocator);
    }
};

/// Public API function to build a parser
pub fn buildParser(writer: std.io.Writer, grammar: *ast.Grammar, options: Options) !void {
    var builder = Builder.init(std.heap.page_allocator, writer, options);
    defer builder.deinit();

    try builder.buildParser(grammar);
}